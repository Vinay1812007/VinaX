// Pure: src/styles/tokens.css (+ the radius scale in index.css) → public/admin/css/tokens.css (UI rebuild Phase 10).
// The owner console is plain static files, so it cannot import the app's CSS;
// this copies the design system's colour-free tokens (space, shape, motion,
// depth, layers) so the two never drift. The console keeps its own colours.
// Run: npm run gen:admin-tokens (src/__tests__/adminTokens.test.ts fails on drift).

const SHARED = /^--(space-\d+|gutter|radius-[\w]+|dur-[\w]+|ease-[\w]+|press-scale|elev-\d|z-[\w]+|leading-[\w]+|tracking-[\w]+|type-(title|body-lg|overline))$/;

/** `--name: value;` pairs of the first `selector {…}` block (one level of braces). */
function decls(css, selector) {
  const at = css.indexOf(`${selector} {`);
  if (at < 0) return [];
  const body = css.slice(css.indexOf('{', at) + 1, css.indexOf('\n}', at));
  const out = [];
  for (const m of body.replace(/\/\*[\s\S]*?\*\//g, '').matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) out.push([m[1], m[2].trim()]);
  return out;
}

/** Keep a shared token only if every var() it reads is also shared. */
function keep(pairs) {
  const names = new Set(pairs.filter(([n]) => SHARED.test(n)).map(([n]) => n));
  return pairs.filter(([n, v]) => names.has(n) && [...v.matchAll(/var\((--[\w-]+)/g)].every((m) => names.has(m[1])));
}

export function buildAdminTokens(tokensCss, indexCss = '') {
  // The base radius scale still lives in index.css; the rest in tokens.css.
  const baseRadii = decls(indexCss, ':root').filter(([n]) => /^--radius-(sm|md|lg|xl|pill)$/.test(n));
  const root = keep([...baseRadii, ...decls(tokensCss, ':root')]);
  const rootNames = new Set(root.map(([n]) => n));
  const light = decls(tokensCss, 'html.light').filter(([n]) => rootNames.has(n));
  const reduce = decls(tokensCss, 'html.reduce-motion').filter(([n]) => rootNames.has(n));
  const line = ([n, v]) => `  ${n}: ${v};`;
  return `/* GENERATED by scripts/admin-tokens.mjs from src/styles/tokens.css — do not edit.
   The app's colour-free design tokens for the owner console (UI rebuild
   Phase 10): space, shape, motion, depth and layers, so the console and the
   app share one system. The console's own colours stay in console.css. */
:root {
${root.map(line).join('\n')}
}
html.light {
${light.map(line).join('\n')}
}
@supports not (transition-timing-function: linear(0, 1)) {
  :root {
    --ease-spring: var(--ease-enter);
    --ease-bounce: cubic-bezier(0.34, 1.56, 0.64, 1);
  }
}
html.reduce-motion {
${reduce.map(line).join('\n')}
}
@media (prefers-reduced-motion: reduce) {
  :root {
${reduce.map((p) => '  ' + line(p)).join('\n')}
  }
}
`;
}
